# append and insert

numbers=[11,12,13,14]
print(numbers)
numbers.append(15)
numbers.append(16)
print(numbers)
numbers.insert(0,100)
print(numbers)
nums=[10,20,10,10]
nums.remove(10)     # remove first matching element
print(nums)
nums.pop()          # remove last element
print(nums)
nums.append(60)
nums.append(70)
nums.append(80)
print(nums)
nums.clear()
print(nums)